import Foundation

let fixtures = URL(fileURLWithPath: CommandLine.arguments[1], isDirectory: true)
let epub = try ListeningBook.open(fixtures.appendingPathComponent("ordered.epub"))
let first = try epub.segments(at: 0).joined()
let second = try epub.segments(at: 1).joined()
precondition(epub.titles.count == 2)
precondition(first.contains("第一章") && first.contains("春天 & 花朵") && !first.contains("不应出现"))
precondition(second.contains("第二章") && second.contains("夏天"))
let txt = try ListeningBook.open(fixtures.appendingPathComponent("gb18030.txt"))
precondition(txt.titles == ["第一章 春天"])
let lines = try txt.segments(at: 0)
precondition(lines == ["第一章 春天", "这是中文正文，不能误判为 UTF-16。"])
let long = String(repeating: "甲", count: 350)
let pieces = try ListeningBook.text([("正文", long)]).segments(at: 0)
precondition(pieces.map { $0.count } == Array(repeating: 32, count: 10) + [30] && pieces.joined() == long)
print("EPUB spine, XHTML, GB18030 and narration segments passed")
